const query = value => new URLSearchParams(value);
const call = (state, path, body = {}, params = '') => routeApi(state, path, query(params), body, 'POST');
function request(server, path, body, method = body === undefined ? 'GET' : 'POST') {
  const req = Readable.from(body === undefined ? [] : [Buffer.from(JSON.stringify(body))]);
  req.url = path; req.method = method;
  return new Promise((resolve, reject) => {
    const res = { writeHead(status, headers) { this.status = status; this.headers = headers; }, end(text) { try { resolve({ status: this.status, body: JSON.parse(text) }); } catch (error) { reject(error); } } };
    server.emit('request', req, res);
  });
}
